/* ══ Active language ══ */
let currentLang = localStorage.getItem('jyotisha_lang') || 'en';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) ||
    (I18N['en'] && I18N['en'][key]) ||
    key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('jyotisha_lang', lang);
  document.documentElement.setAttribute('data-lang', lang);

  const flags = { en: '🇬🇧', te: '🇮🇳', hi: '🇮🇳', ta: '🇮🇳', ml: '🇮🇳', kn: '🇮🇳', mr: '🇮🇳' };
  const codes = { en: 'EN', te: 'TE', hi: 'HI', ta: 'TA', ml: 'ML', kn: 'KN', mr: 'MR' };
  document.getElementById('currentLangFlag').textContent = flags[lang] || '🇮🇳';
  document.getElementById('currentLangCode').textContent = codes[lang] || 'EN';

  applyTranslations();
  closeLangMenu();

  // Re-render dynamic sections
  if (window.renderRasiGrid) renderRasiGrid();
  if (window.renderRasiChips) renderRasiChips();
}

function toggleLangMenu() {
  const menu = document.getElementById('langMenu');
  menu.classList.toggle('hidden');
}

function closeLangMenu() {
  document.getElementById('langMenu').classList.add('hidden');
}

// Close lang menu on outside click
document.addEventListener('click', e => {
  const ls = document.getElementById('langSwitcher');
  if (ls && !ls.contains(e.target)) closeLangMenu();
});

// Init
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
});

// Make functions globally accessible for HTML onclick handlers
window.setLanguage = setLanguage;
window.toggleLangMenu = toggleLangMenu;
window.t = t;
window.currentLang = currentLang;